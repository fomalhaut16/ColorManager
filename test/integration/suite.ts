import * as vscode from 'vscode';
import { writeFileSync } from 'node:fs';
import { auditCoverage } from '../../src/dev/auditCoverage';

// Entry point loaded by @vscode/test-electron inside the isolated instance.

const ROOT = process.env.CM_ROOT!;

async function dumpRegistryTask(): Promise<void> {
  const out = vscode.Uri.file(`${ROOT}/data/color-registry.core.json`);
  await vscode.commands.executeCommand('colorManager.dev.dumpRegistry', out);
}

async function auditLiteralsTask(): Promise<void> {
  // Explicit rules only: whatever still does not follow the hue has a literal VS Light value.
  const r = await auditCoverage({ literals: new Set() });
  const out = { note: 'generated by node test/integration/run.mjs audit-literals', vscodeVersion: vscode.version, ids: r.leaks.map((l) => l.id) };
  writeFileSync(`${ROOT}/data/color-literals.json`, JSON.stringify(out, null, 2) + '\n');
  console.log(`[audit-literals] written ${r.written}, literal ids ${r.leaks.length}`);
}

async function auditTask(): Promise<void> {
  const r = await auditCoverage();
  const out = { vscodeVersion: vscode.version, written: r.written, leaks: r.leaks };
  writeFileSync(`${ROOT}/data/coverage-report.json`, JSON.stringify(out, null, 2) + '\n');
  console.log(`[audit] written ${r.written}, leaks ${r.leaks.length}`);
  for (const l of r.leaks) console.log(`[audit]   ${l.id} ${l.value}`);
}

export async function run(): Promise<void> {
  // Wait for our extension to activate.
  const ext = vscode.extensions.getExtension('local.colormanager');
  if (!ext) throw new Error('extension local.colormanager not found');
  await ext.activate();
  switch (process.env.CM_TASK) {
    case 'dump-registry':
      return dumpRegistryTask();
    case 'audit-literals':
      return auditLiteralsTask();
    case 'audit':
      return auditTask();
    default:
      throw new Error(`unknown task ${process.env.CM_TASK}`);
  }
}
