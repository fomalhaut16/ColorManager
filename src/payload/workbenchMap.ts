import type { RoleName } from '../palette/roles';

// Workbench color id -> role (plan 7.3). Rules are evaluated top to bottom;
// the first match wins. Ids that match nothing are not written; the coverage
// audit (plan 7.4) lists ids that still show Visual Studio Light values.

export interface Rule {
  match: string | RegExp;
  role: RoleName | ((id: string) => RoleName | undefined);
  /** Alpha to start from when writing a translucent color (plan 6.11). */
  alpha?: number;
  /** Background the translucent color sits on (default: editor.bg). */
  over?: RoleName;
  /** Blend the role color toward `over` (1 = role color, 0 = background). */
  weight?: number;
  /** Generic fallbacks never apply to ids whose VS Light value is null. */
  fallback?: boolean;
}

const ANSI: Record<string, RoleName> = {
  Black: 'ansi.black',
  Red: 'ansi.red',
  Green: 'ansi.green',
  Yellow: 'ansi.yellow',
  Blue: 'ansi.blue',
  Magenta: 'ansi.magenta',
  Cyan: 'ansi.cyan',
  White: 'ansi.white',
};

export function ansiRole(id: string): RoleName | undefined {
  const m = /^terminal\.ansi(Bright)?(Black|Red|Green|Yellow|Blue|Magenta|Cyan|White)$/.exec(id);
  if (!m) return undefined;
  return (m[1] ? `ansi.bright${m[2]}` : ANSI[m[2]!]) as RoleName;
}

export function bracketRole(id: string): RoleName | undefined {
  const m = /^editorBracketHighlight\.foreground([1-6])$/.exec(id);
  return m ? (`bracket.${m[1]}` as RoleName) : undefined;
}

const SYMBOL_ROLES: Array<[RegExp, RoleName]> = [
  [/^(function|method|constructor|event)$/, 'tok.function'],
  [/^(class|interface|struct|typeParameter|namespace|module|package|enum)$/, 'tok.type'],
  [/^(variable|field|property|key)$/, 'tok.property'],
  [/^(constant|number|boolean|enumerator|enumeratorMember|enumMember|null)$/, 'tok.number'],
  [/^string$/, 'tok.string'],
  [/^(keyword|operator)$/, 'tok.keyword'],
];

export function symbolIconRole(id: string): RoleName | undefined {
  const m = /^(?:symbolIcon|terminalSymbolIcon)\.(\w+?)Foreground$/.exec(id);
  if (!m) return undefined;
  return SYMBOL_ROLES.find(([re]) => re.test(m[1]!))?.[1] ?? 'fg.secondary';
}

/** Semantic keywords inside an id -> status role. */
function statusRole(id: string): RoleName | undefined {
  const name = id;
  if (/(error|Error|failed|Failed|deleted|Deleted|removed|Removed|conflict|Conflict|invalid|Invalid|stop|Stop|disconnect|Disconnect|breakpoint(?!Unverified)|Breakpoint(?!Unverified))/.test(name)) return 'status.error';
  if (/(warning|Warning|modified|Modified|changed|Changed|edited|Edited|queued|Queued|pause|Pause)/.test(name)) return 'status.warning';
  if (/(added|Added|inserted|Inserted|passed|Passed|success|Success|untracked|Untracked|start|Start|restart|Restart|running|Running)/.test(name)) return 'status.success';
  if (/(info|Info|renamed|Renamed|submodule|Submodule|step|Step|continue|Continue)/.test(name)) return 'status.info';
  return undefined;
}

